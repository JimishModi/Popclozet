const fs = require('fs');
const path = require('path');
const { PDFParse } = require('pdf-parse');

const extract = async () => {
    try {
        const termsPath = path.resolve(__dirname, 'docs', 'Terms & condition_popclozet.pdf');
        const cookiesPath = path.resolve(__dirname, 'docs', 'Cookies policy.pdf');
        const privacyPath = path.resolve(__dirname, 'docs', 'Privacy policy.pdf');

        const parsePdf = async (filePath) => {
            console.log(`  Parsing: ${path.basename(filePath)}`);
            const p = new PDFParse({ url: filePath });
            await p.load();
            const result = await p.getText();
            return result.text;
        };

        console.log("Extracting PDFs...");
        const termsText = await parsePdf(termsPath);
        const cookiesText = await parsePdf(cookiesPath);
        const privacyText = await parsePdf(privacyPath);

        const formatString = (str) => {
            return str
                .replace(/\n-- \d+ of \d+ --\n/g, '\n')  // Remove page markers
                .replace(/\\/g, '\\\\')
                .replace(/`/g, '\\`')
                .replace(/\$/g, '\\$')
                .replace(/\r\n/g, '\n')
                .replace(/\n\n+/g, '\n\n')
                .trim();
        };

        const tsContent = `// Auto-generated by extractPdf.cjs — do not edit manually.
export const TERMS_AND_CONDITIONS = \`
${formatString(termsText)}
\`;

export const COOKIE_POLICY = \`
${formatString(cookiesText)}
\`;

export const PRIVACY_POLICY = \`
${formatString(privacyText)}
\`;
`;

        const outDir = path.join(__dirname, 'apps', 'customer-app', 'src', 'constants');
        if (!fs.existsSync(outDir)) {
            fs.mkdirSync(outDir, { recursive: true });
        }

        fs.writeFileSync(path.join(outDir, 'legalDocs.ts'), tsContent);
        console.log("Done! Generated:", path.join(outDir, 'legalDocs.ts'));
    } catch (err) {
        console.error("Extraction failed:", err);
        process.exit(1);
    }
};

extract();
